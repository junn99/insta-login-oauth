@dataclass(frozen=True)
class ConsentAcceptance:
    """The consent snapshot accepted immediately before OAuth redirect."""

    accepted_at: datetime
    age_confirmed: bool
    terms_accepted: bool
    privacy_accepted: bool
    instagram_permissions_accepted: bool
    consent_schema_version: int = CONSENT_SCHEMA_VERSION
    terms_version: str = TERMS_VERSION
    privacy_version: str = PRIVACY_VERSION
    instagram_permissions_version: str = INSTAGRAM_PERMISSIONS_VERSION

    @classmethod
    def accepted_now(cls) -> "ConsentAcceptance":
        return cls(
            accepted_at=datetime.now(timezone.utc),
            age_confirmed=True,
            terms_accepted=True,
            privacy_accepted=True,
            instagram_permissions_accepted=True,
        )

    @classmethod
    def from_mapping(cls, value: dict[str, Any]) -> "ConsentAcceptance":
        return cls(
            accepted_at=_parse_datetime(value.get("accepted_at")),
            age_confirmed=_require_true(value, "age_confirmed"),
            terms_accepted=_require_true(value, "terms_accepted"),
            privacy_accepted=_require_true(value, "privacy_accepted"),
            instagram_permissions_accepted=_require_true(
                value,
                "instagram_permissions_accepted",
            ),
            consent_schema_version=CONSENT_SCHEMA_VERSION,
            terms_version=_require_exact(value, "terms_version", TERMS_VERSION),
            privacy_version=_require_exact(value, "privacy_version", PRIVACY_VERSION),
            instagram_permissions_version=_require_exact(
                value,
                "instagram_permissions_version",
                INSTAGRAM_PERMISSIONS_VERSION,
            ),
        )

    def to_payload(self) -> dict[str, Any]:
        payload = asdict(self)
        payload.pop("consent_schema_version", None)
        payload["accepted_at"] = self.accepted_at.isoformat()
        return payload

    @property
    def channel_data_accepted(self) -> bool:
        return self.instagram_permissions_accepted


def _parse_datetime(value: Any) -> datetime:
    if isinstance(value, datetime):
        parsed = value
    elif isinstance(value, str) and value:
        parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
    else:
        raise ValueError("accepted_at is required")
    if parsed.tzinfo is None:
        raise ValueError("accepted_at timezone is required")
    return parsed


def _require_true(value: dict[str, Any], key: str) -> bool:
    if value.get(key) is not True:
        raise ValueError(f"{key} must be true")
    return True


def _require_exact(value: dict[str, Any], key: str, expected: str) -> str:
    item = value.get(key)
    if item != expected:
        raise ValueError(f"{key} must be {expected}")
    return item


def canonical_json(value: dict[str, Any]) -> str:
    """Serialize payloads for stable hashing and signing."""
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"), sort_keys=True)


def consent_bundle_hash(payload: dict[str, Any]) -> str:
    """Hash consent contents, excluding transport-only state fields."""
    consent_items = {
        key: value
        for key, value in payload.items()
        if key not in {"iat", "nonce", "binding_id", "bundle_hash"}
    }
    return hashlib.sha256(canonical_json(consent_items).encode("utf-8")).hexdigest()


def consent_payload(acceptance: ConsentAcceptance | dict[str, Any]) -> dict[str, Any]:
    """Return the versioned payload embedded in OAuth state."""
    if isinstance(acceptance, dict):
        normalized = ConsentAcceptance.from_mapping(acceptance)
    elif isinstance(acceptance, ConsentAcceptance):
        normalized = ConsentAcceptance.from_mapping(acceptance.to_payload())
    else:
        raise TypeError("consent must be a ConsentAcceptance or mapping")
    return normalized.to_payload()
